import { createHash } from "node:crypto";
import { readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist");
const base = "/ttugae/";

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else if (entry.name !== "sw.js" && entry.name !== ".nojekyll") files.push(full);
  }
  return files;
}

function toUrl(file) {
  const rel = path.relative(dist, file).split(path.sep).map(encodeURIComponent).join("/");
  return `${base}${rel}`;
}

const files = (await walk(dist)).sort();
const hash = createHash("sha256");
for (const file of files) {
  const info = await stat(file);
  hash.update(toUrl(file));
  hash.update(String(info.size));
  hash.update(String(Math.round(info.mtimeMs)));
}
const version = hash.digest("hex").slice(0, 12);
const urls = files.map(toUrl);

const source = `/* Generated by scripts/write-precache-sw.mjs. Cache ${version}, ${urls.length} files. */
const VERSION = ${JSON.stringify(version)};
const CACHE = "ttugae-" + VERSION;
const BASE = "/ttugae/";
const URLS = ${JSON.stringify(urls)};
const FONT_CSS = [
  "https://cdn.jsdelivr.net/gh/orioncactus/pretendard@v1.3.9/dist/web/static/pretendard.min.css",
  "https://fonts.googleapis.com/css2?family=Noto+Sans+KR:wght@400;500;600;700&display=swap",
];
const RUNTIME_HOSTS = new Set([
  "cdn.jsdelivr.net",
  "fonts.googleapis.com",
  "fonts.gstatic.com",
  "tile.openstreetmap.de",
]);
const DONE = new Request(BASE + "__precache_done__");
const MISSING = new Request(BASE + "__precache_missing__");

let filling = null;

self.addEventListener("install", (event) => {
  event.waitUntil(self.skipWaiting());
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    self.clients.claim().then(() => ensureFilled()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data !== "precache") return;
  event.waitUntil(ensureFilled());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin === self.location.origin) {
    if (url.pathname === BASE + "sw.js") return;
    if (!url.pathname.startsWith(BASE)) return;
    event.respondWith(fromCache(request));
    return;
  }
  if (RUNTIME_HOSTS.has(url.hostname)) {
    event.respondWith(fromCache(request));
  }
});

function ensureFilled() {
  if (!filling) {
    filling = fill().finally(() => {
      filling = null;
    });
  }
  return filling;
}

async function fill() {
  try {
    await fillCache();
  } catch {
    // The next page message starts the same pass again. Files already stored are skipped.
  }
}

async function fillCache() {
  const cache = await caches.open(CACHE);
  if (await cache.match(DONE)) {
    await notify("precache-done");
    return;
  }
  const missing = await readMissing(cache);
  let quota = false;
  let incomplete = false;
  for (let index = 0; index < URLS.length; index += 1) {
    const url = URLS[index];
    if (missing.has(url) || (await cache.match(url))) continue;
    const result = await putUrl(cache, url);
    if (result === "missing") missing.add(url);
    if (result === "retry") incomplete = true;
    if (result === "quota") {
      quota = true;
      break;
    }
    if (url.endsWith("/index.html")) {
      const dir = url.slice(0, -"index.html".length);
      const saved = await cache.match(url);
      if (saved) await cache.put(dir, saved.clone());
    }
  }
  await cache.put(MISSING, jsonResponse([...missing]));
  if (quota || incomplete) return;
  for (const cssUrl of FONT_CSS) {
    const stored = await cacheFontCss(cache, cssUrl);
    if (!stored) return;
  }
  await cache.put(DONE, jsonResponse({ version: VERSION, at: Date.now() }));
  await deleteOtherCaches();
  await notify("precache-done");
}

async function putUrl(cache, url) {
  if (await cache.match(url)) return "ok";
  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      const response = await fetch(url);
      if (response.ok) {
        await cache.put(url, response);
        return "ok";
      }
      if (response.status === 404 || response.status === 410) return "missing";
    } catch (error) {
      if (error && error.name === "QuotaExceededError") return "quota";
    }
    await wait(500 * (attempt + 1));
  }
  return "retry";
}

async function cacheFontCss(cache, cssUrl) {
  try {
    let response = await cache.match(cssUrl);
    if (!response) {
      response = await fetch(cssUrl, { mode: "cors" });
      if (!response.ok) return false;
      await cache.put(cssUrl, response.clone());
    }
    const text = await response.clone().text();
    const found = text.match(/url\\(([^)]+)\\)/g) || [];
    for (const raw of found) {
      const inner = raw.slice(4, -1).replace(/["']/g, "").trim();
      if (!inner || inner.startsWith("data:")) continue;
      const fontUrl = new URL(inner, cssUrl).href;
      if (await cache.match(fontUrl)) continue;
      const font = await fetch(fontUrl, { mode: "cors" });
      if (!font.ok) return false;
      await cache.put(fontUrl, font);
    }
    return true;
  } catch {
    return false;
  }
}

async function fromCache(request) {
  const url = new URL(request.url);
  const cached = await matchAny(request);
  if (cached) {
    const range = request.headers.get("range");
    if (range) {
      const partial = await sliceRange(cached, range);
      if (partial) return partial;
    }
    return cached;
  }
  try {
    const response = await fetch(request);
    if (response.ok && response.status !== 206) {
      try {
        const cache = await caches.open(CACHE);
        await cache.put(request, response.clone());
      } catch {
        // The network response is still returned when the disk cache is full.
      }
    }
    return response;
  } catch {
    if (request.mode === "navigate") {
      const fallback = url.pathname.startsWith(BASE + "app")
        ? await matchAny(BASE + "app/")
        : await matchAny(BASE);
      if (fallback) return fallback;
    }
    return new Response("", { status: 503, statusText: "Offline" });
  }
}

async function matchAny(request) {
  const current = await caches.open(CACHE);
  const hit = await current.match(request, { ignoreSearch: true, ignoreVary: true });
  if (hit) return hit;
  const names = await caches.keys();
  for (const name of names) {
    if (name === CACHE) continue;
    const found = await (await caches.open(name)).match(request, { ignoreSearch: true, ignoreVary: true });
    if (found) return found;
  }
  return null;
}

async function sliceRange(response, range) {
  const match = /bytes=(\\d+)-(\\d*)/.exec(range);
  if (!match) return null;
  const buffer = await response.clone().arrayBuffer();
  const start = Number(match[1]);
  const end = match[2] ? Number(match[2]) : buffer.byteLength - 1;
  if (start > end || start >= buffer.byteLength) return null;
  const slice = buffer.slice(start, end + 1);
  const headers = new Headers(response.headers);
  headers.set("Content-Range", "bytes " + start + "-" + end + "/" + buffer.byteLength);
  headers.set("Content-Length", String(slice.byteLength));
  headers.set("Accept-Ranges", "bytes");
  const type = response.headers.get("Content-Type");
  if (type) headers.set("Content-Type", type);
  return new Response(slice, { status: 206, statusText: "Partial Content", headers });
}

async function readMissing(cache) {
  const saved = await cache.match(MISSING);
  if (!saved) return new Set();
  try {
    const list = await saved.json();
    return new Set(Array.isArray(list) ? list : []);
  } catch {
    return new Set();
  }
}

async function deleteOtherCaches() {
  const names = await caches.keys();
  await Promise.all(names.filter((name) => name !== CACHE).map((name) => caches.delete(name)));
}

async function notify(message) {
  const clients = await self.clients.matchAll({ includeUncontrolled: true });
  for (const client of clients) client.postMessage(message);
}

function jsonResponse(value) {
  return new Response(JSON.stringify(value), { headers: { "Content-Type": "application/json" } });
}

function wait(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
`;

await writeFile(path.join(dist, "sw.js"), source);
console.log(`precache sw ${version} (${urls.length} files)`);
